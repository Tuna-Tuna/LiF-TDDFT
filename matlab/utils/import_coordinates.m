%% Read data columns according to format string.
dataArray = textscan(fileID, formatSpec, endRow(1)-startRow(1)+1, ...
    'Delimiter', '', 'WhiteSpace', '', 'TextType', 'string', ...
    'EmptyValue', NaN, 'HeaderLines', startRow(1)-1, ...
    'ReturnOnError', false, 'EndOfLine', '\r\n');
for block = 2:length(startRow)
    frewind(fileID);
    dataArrayBlock = textscan(fileID, formatSpec, ...
        endRow(block)-startRow(block)+1, 'Delimiter', '', ...
        'WhiteSpace', '', 'TextType', 'string', 'EmptyValue', NaN, ...
        'HeaderLines', startRow(block)-1, 'ReturnOnError', false, ...
        'EndOfLine', '\r\n');
    for col = 1:length(dataArray)
        dataArray{col} = [dataArray{col}; dataArrayBlock{col}];
    end
end

%% Close the text file.
fclose(fileID);

%% Assemble output matrix and remove trailing NaN-only columns.
